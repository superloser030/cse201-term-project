# ============================================================
#  Report section 7: concatenate all source files into one Markdown file.
#  Output: docs\report\source_listing.md
#  Run:    powershell -NoProfile -ExecutionPolicy Bypass -File docs\report\make_listing.ps1
# ============================================================
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$src = Join-Path $root "src"
$out = Join-Path $PSScriptRoot "source_listing.md"
$utf8 = New-Object System.Text.UTF8Encoding($false)

# main.cpp first, then each folder: header before its .cpp
$files = @(Get-Item (Join-Path $src "main.cpp"))
foreach ($dir in @("system", "bank", "atm", "transaction", "common")) {
    $all = Get-ChildItem (Join-Path $src $dir) -File | Where-Object { $_.Extension -in ".h", ".cpp" }
    $names = $all | ForEach-Object { $_.BaseName } | Sort-Object -Unique
    foreach ($n in $names) {
        $files += $all | Where-Object { $_.BaseName -eq $n } | Sort-Object { if ($_.Extension -eq ".h") { 0 } else { 1 } }
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# Source Code Listing")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("Generated by docs/report/make_listing.ps1 ($($files.Count) files)")
[void]$sb.AppendLine("")
foreach ($f in $files) {
    $rel = $f.FullName.Substring($root.Length + 1).Replace("\", "/")
    [void]$sb.AppendLine("## $rel")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine('```cpp')
    [void]$sb.AppendLine([System.IO.File]::ReadAllText($f.FullName, $utf8).TrimEnd())
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine("")
}
[System.IO.File]::WriteAllText($out, $sb.ToString(), $utf8)
Write-Host "Wrote $out ($($files.Count) files)"
